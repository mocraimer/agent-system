const operator = 'ui-e2e@example.test';

type ApiPayload = {
  approvals?: { id: string }[];
  jobs?: { id: string; taskId: string }[];
  runs?: { run: { id: string; status: string } }[];
  reservations?: { runId: string }[];
};

async function initState(state: string): Promise<void> {
  await run(process.execPath, ['dist/cli/main.js', 'init', '--operator', operator], {
    cwd: root,
    env: { ...process.env, AGENTSYS_STATE: state },
  });
}

async function waitForUrl(child: ChildProcessWithoutNullStreams): Promise<string> {
  return await new Promise((resolve, reject) => {
    let output = '';
    const timer = setTimeout(() => reject(new Error(`UI server did not print a URL. Output: ${output}`)), 15_000);
    const onData = (chunk: Buffer): void => {
      output += chunk.toString('utf8');
      const match = /Agent system UI listening at (http:\/\/127\.0\.0\.1:\d+\/#bootstrap=[^\s]+)/.exec(output);
      if (match) {
        clearTimeout(timer);
        child.stdout.off('data', onData);
        resolve(match[1]!);
      }
    };
    child.stdout.on('data', onData);
    child.once('error', reject);
    child.once('exit', (code) => { if (code !== null && code !== 0) reject(new Error(`UI server exited ${code}: ${output}`)); });
  });
}

async function apiJson(page: Page, path: string): Promise<ApiPayload> {
  return page.evaluate(async (requestPath: string) => {
    const response = await fetch(requestPath);
    return response.json();
  }, path) as Promise<ApiPayload>;
}

class BrowserFakeAdapter implements RuntimeAdapter {
  readonly capabilities: RuntimeCapabilities = {
    runtime: 'pi-local',
    subscriptionId: 'ui-test-subscription',
    supportsModelSelection: true,
    supportsEffortSelection: true,
    effortLevels: ['low', 'high'],
    reportsEffectiveSettings: true,
    acceptsCallerSessionId: true,
    skillInvocationForm: '/skill:fake <task>',
  };
  mode: 'normal' | 'quota' | 'remote' = 'normal';
  usageCalls = 0;
  readinessCalls = 0;
  dispatchCalls = 0;
  reconcileCalls = 0;

  readUsage(): Promise<UsageResult> {
    this.usageCalls++;
    const usedPercent = this.mode === 'quota' ? 100 : 1;
    return Promise.resolve({
      ok: true,
      reading: {
        subscriptionId: this.capabilities.subscriptionId,
        observedAt: new Date().toISOString(),
        source: 'browser fake adapter',
        windows: [
          { kind: 'five-hour', usedPercent, vendorLabel: 'five-hour', resetsAt: '2099-01-01T00:00:00.000Z' },
          { kind: 'weekly', usedPercent, vendorLabel: 'weekly', resetsAt: '2099-01-02T00:00:00.000Z' },
        ],
      },
    });
  }

  checkReadiness(): Promise<Outcome | undefined> {
    this.readinessCalls++;
    return Promise.resolve(undefined);
  }

  dispatch(input: DispatchInput): Promise<DispatchResult> {
    this.dispatchCalls++;
    mkdirSync(input.evidenceDir, { recursive: true });
    writeFileSync(join(input.evidenceDir, 'fake-evidence.txt'), 'evidence generated by fake adapter\n', 'utf8');
    if (this.mode === 'remote') {
      return Promise.resolve({
        outcome: {
          kind: 'remote-uncertain',
          taskId: input.taskId,
          runId: input.runId,
          summary: 'The fake runtime did not confirm the remote session.',
          nextAction: 'Inspect the fake session and reconcile before retrying.',
        },
        sessionId: 'fake-session-uncertain',
        settings: {
          requested: { model: input.settings.model ?? 'vendor-default', effort: input.settings.effort ?? 'vendor-default' },
          resolved: { model: input.settings.model ?? 'fake-model', effort: input.settings.effort ?? 'high' },
          observed: { model: 'fake-model', effort: 'high' },
        },
      });
    }
    return Promise.resolve({
      outcome: {
        kind: 'completed',
        taskId: input.taskId,
        runId: input.runId,
        summary: 'The fake runtime completed the isolated browser task.',
        nextAction: 'Review the retained evidence.',
      },
      settings: {
        requested: { model: input.settings.model ?? 'vendor-default', effort: input.settings.effort ?? 'vendor-default' },
        resolved: { model: input.settings.model ?? 'fake-model', effort: input.settings.effort ?? 'high' },
        observed: { model: 'fake-model', effort: 'high' },
      },
    });
  }

  reconcile(): Promise<Outcome> {
    this.reconcileCalls++;
    return Promise.resolve({
      kind: 'remote-uncertain',
      summary: 'The fake remote session is still uncertain.',
      nextAction: 'Inspect the fake session before starting another attempt.',
    });
  }
}

async function fillDispatch(page: Page, values: Record<string, string>): Promise<void> {
  const form = page.locator('section.panel').filter({ hasText: 'Dispatch an approved task' }).locator('form');
  for (const [label, value] of Object.entries({
    'Task ID': values.taskId,
    Repository: 'example/consumer',
    'Work class': 'ci-repair',
    Runtime: 'pi-local',
    Profile: 'default',
    'Approval ID': values.approvalId ?? '',
    'Existing job ID (optional)': values.jobId ?? '',
    'Trigger source (optional)': values.triggerSource ?? '',
    Prompt: 'run the isolated browser task',
    'Estimate: five-hour %': '1',
    'Estimate: weekly %': '1',
    'Uncertainty %': '1',
    'Estimate basis detail': 'bounded browser test estimate',
    'Estimate basis': 'operator-bound',
  })) {
    await form.getByLabel(label, { exact: true }).fill(value);
  }
  await form.locator('input[type="checkbox"][value="author-changes"]').check();
  await form.getByRole('button', { name: 'Dispatch', exact: true }).click();
}

async function createApproval(page: Page): Promise<string> {
  await page.getByRole('button', { name: 'Authority' }).click();
  const form = page.locator('form').filter({ hasText: 'Create approval' });
  await form.getByLabel('Repository').fill('example/consumer');
  await form.getByLabel('Scope').fill('run the isolated browser task');
  await form.getByLabel('Work class').fill('ci-repair');
  await form.getByLabel('Runtime').fill('pi-local');
  await form.getByLabel('Profile').fill('default');
  await form.getByLabel('Actions (comma-separated)').fill('author-changes');
  await form.getByLabel('Max attempts').fill('3');
  await form.getByRole('button', { name: 'Create approval', exact: true }).click();
  await expect(form.locator('pre.output')).toBeVisible();
  const authority = await apiJson(page, '/api/authority');
  const approval = authority.approvals?.at(-1);
  if (!approval) throw new Error('The browser did not create an approval.');
  return approval.id;
}

async function createJob(page: Page): Promise<{ id: string; taskId: string }> {
  const form = page.locator('form').filter({ hasText: 'Record CI failure' });
  const fields: Record<string, string> = {
    'Event source': 'github-actions:example/consumer',
    Repository: 'example/consumer',
    'Workflow name': 'isolated-checks',
    'CI run ID': 'browser-run-1',
    'Head SHA': '0123456789abcdef',
    Branch: 'dev',
    Conclusion: 'failure',
    'Failure title': 'fake failure',
    'Failure summary': 'fake summary',
    'Work class': 'ci-repair',
    Runtime: 'pi-local',
    Profile: 'default',
    'Actions (comma-separated)': 'author-changes',
    'Obligations (comma-separated)': 'verification',
  };
  for (const [label, value] of Object.entries(fields)) await form.getByLabel(label).fill(value);
  await form.getByRole('button', { name: 'Record CI failure', exact: true }).click();
  await expect(form.locator('pre.output')).toBeVisible();
  const jobs = await apiJson(page, '/api/jobs');
  const job = jobs.jobs?.at(-1);
  if (!job) throw new Error('The browser did not create an intake job.');
  return { id: job.id, taskId: job.taskId };
}

test('boots the real local UI and navigates its operator surfaces', async ({ page }) => {
  test.setTimeout(60_000);
  const state = mkdtempSync(join(tmpdir(), 'agentsys-ui-cli-e2e-'));
  const env = { ...process.env, AGENTSYS_STATE: state };
  const child = spawn(process.execPath, ['dist/cli/main.js', 'ui'], { cwd: root, env, stdio: ['ignore', 'pipe', 'pipe'] });
  try {
    await run(process.execPath, ['dist/cli/main.js', 'init', '--operator', operator], { cwd: root, env });
    const url = await waitForUrl(child);
    await page.goto(url);
    await expect(page.getByRole('heading', { name: 'Agent system control' })).toBeVisible();
    await expect(page.getByText('Approval-only operation.')).toBeVisible();
    await page.reload();
    await expect(page.getByText('Approval-only operation.')).toBeVisible();

    await page.getByRole('button', { name: 'Work' }).click();
    await expect(page.getByRole('heading', { name: 'Work queue' })).toBeVisible();
    await expect(page.getByText('No runs recorded.')).toBeVisible();

    await page.getByRole('button', { name: 'Authority' }).click();
    await expect(page.getByRole('heading', { name: 'Approvals' })).toBeVisible();
    await expect(page.getByText('No approvals recorded.')).toBeVisible();

    await page.getByRole('button', { name: 'Evidence' }).click();
    await expect(page.getByText('No required checks are configured; acceptance is unavailable.')).toBeVisible();
  } finally {
    child.kill('SIGTERM');
    rmSync(state, { recursive: true, force: true });
  }
});

test('drives the control workflow with isolated fake adapters and survives restart', async ({ page }) => {
  test.setTimeout(60_000);
  const state = mkdtempSync(join(tmpdir(), 'agentsys-ui-fake-e2e-'));
  process.env.AGENTSYS_STATE = state;
  const fake = new BrowserFakeAdapter();
  const commands = createCoordinatorCommands(() => fake);
  await initState(state);
  let server = await startUiServer({ repoRoots: [root], commands });
  try {
    await page.goto(server.url);
    await expect(page.getByRole('heading', { name: 'Agent system control' })).toBeVisible();

    // A pending request is rendered and stops before usage or runtime dispatch.
    await page.getByRole('button', { name: 'Work' }).click();
    await fillDispatch(page, { taskId: 'task-pending' });
    await expect(page.locator('#operation-status')).toContainText('Awaiting approval');
    await expect(page.locator('#operation-status')).toContainText('Adapter invoked: no');
    expect(fake.usageCalls).toBe(0);
    expect(fake.dispatchCalls).toBe(0);

    const approvalId = await createApproval(page);

    // An approved task reaches only the injected adapter, writes bounded evidence, and produces a scorecard.
    await page.getByRole('button', { name: 'Work' }).click();
    await fillDispatch(page, { taskId: 'task-completed', approvalId });
    await expect(page.locator('#operation-status')).toContainText('Completed');
    await expect(page.locator('#operation-status')).toContainText('Adapter invoked: yes');
    expect(fake.dispatchCalls).toBe(1);
    const completedStatus = await apiJson(page, '/api/status?taskId=task-completed');
    const completedRun = completedStatus.runs?.[0]?.run;
    if (!completedRun) throw new Error('The approved browser dispatch did not persist a run.');
    expect(completedRun.status).toBe('completed');

    commands.reviewRecord({ kind: 'operator', id: operator }, 'card_task-completed', {
      author: 'author', reviewer: { id: 'reviewer', relationship: 'independent' },
      source: 'browser-test', head: 'a'.repeat(40), findings: [{ severity: 'high', summary: 'detail-only browser finding' }],
    });
    const overview = await apiJson(page, '/api/overview');
    expect(JSON.stringify(overview)).not.toMatch(/detail-only browser finding|reviewerFindings|findingCount/);
    const details = await apiJson(page, '/api/evaluation?view=scorecards');
    expect(JSON.stringify(details)).toContain('detail-only browser finding');

    // Evidence is listed and its content is fetched through the bounded UI route; feedback is attributed.
    await page.getByRole('button', { name: 'Evidence' }).click();
    await page.getByLabel('Run ID').fill(completedRun.id);
    await page.getByRole('button', { name: 'List evidence' }).click();
    await expect(page.locator('strong').filter({ hasText: 'fake-evidence.txt' })).toBeVisible();
    await page.getByRole('button', { name: 'View fake-evidence.txt' }).click();
    await expect(page.getByText('evidence generated by fake adapter')).toBeVisible();
    const feedback = page.locator('form').filter({ hasText: 'Feedback' });
    await feedback.getByLabel('Scorecard ID').fill('card_task-completed');
    await feedback.getByLabel('Verdict (accepted, rework-needed, rejected)').fill('accepted');
    await feedback.getByLabel('Reason').fill('The isolated evidence is attributable.');
    await feedback.getByRole('button', { name: 'Feedback', exact: true }).click();
    await expect(feedback).toContainText(operator);

    // Safety is a real browser interaction, but all runtime calls go to the fake adapter.
    await page.getByRole('button', { name: 'Safety' }).click();
    await expect(page.getByRole('heading', { name: 'Runtime readiness' })).toBeVisible();
    expect(fake.readinessCalls).toBeGreaterThan(0);
    const ledger = page.locator('form').filter({ hasText: 'Set paid-call allowance' });
    await ledger.getByLabel('Allowance USD').fill('25');
    await ledger.getByRole('button', { name: 'Set paid-call allowance', exact: true }).click();
    await expect(ledger).toContainText('25');
    const version = page.locator('form').filter({ hasText: 'Activate a reviewed version' });
    await version.getByLabel('Coordinator identity').fill('coordinator@test-v1');
    await version.getByLabel('Prompt identity').fill('prompts@test-v1');
    await version.getByLabel('Merged PR URL').fill('https://example.test/pr/1');
    await version.getByRole('button', { name: 'Activate a reviewed version', exact: true }).click();
    await expect(version).toContainText(operator);
    await version.getByLabel('Coordinator identity').fill('coordinator@test-v2');
    await version.getByLabel('Prompt identity').fill('prompts@test-v2');
    await version.getByLabel('Merged PR URL').fill('https://example.test/pr/2');
    await version.getByRole('button', { name: 'Activate a reviewed version', exact: true }).click();
    await version.getByRole('button', { name: 'Rollback to previous version', exact: true }).click();
    await expect(version).toContainText(operator);

    // A quota refusal is meaningful history, still stops before dispatch, and is visible in the operation result.
    fake.mode = 'quota';
    await page.getByRole('button', { name: 'Work' }).click();
    await fillDispatch(page, { taskId: 'task-quota', approvalId });
    await expect(page.locator('#operation-status')).toContainText('Waiting on subscription allowance');
    await expect(page.locator('#operation-status')).toContainText('Adapter invoked: no');
    expect(fake.dispatchCalls).toBe(1);
    const quotaStatus = await apiJson(page, '/api/status?taskId=task-quota');
    expect(quotaStatus.runs?.[0]?.run.status).toBe('quota-waiting');

    // Intake creates one durable job. A remote-uncertain dispatch is shown and the same job cannot dispatch twice.
    fake.mode = 'remote';
    const job = await createJob(page);
    await fillDispatch(page, { taskId: job.taskId, approvalId, jobId: job.id });
    await expect(page.locator('#operation-status')).toContainText('Remote state uncertain');
    await expect(page.locator('#operation-status')).toContainText('Adapter invoked: yes');
    expect(fake.dispatchCalls).toBe(2);
    const remoteStatus = await apiJson(page, `/api/status?taskId=${encodeURIComponent(job.taskId)}`);
    const remoteRun = remoteStatus.runs?.[0]?.run;
    if (!remoteRun) throw new Error('The remote-uncertain browser dispatch did not persist a run.');
    expect(remoteStatus.reservations?.some((reservation) => reservation.runId === remoteRun.id)).toBe(true);
    await page.getByRole('button', { name: 'Recover unsettled work' }).click();
    await expect(page.locator('#operation-status')).toContainText('Completed');
    expect(fake.reconcileCalls).toBeGreaterThan(0);

    await server.close();
    server = await startUiServer({ repoRoots: [root], commands });
    await page.goto(server.url);
    await page.getByRole('button', { name: 'Work' }).click();
    await expect(page.getByText('Remote state uncertain')).toBeVisible();
    const restartedStatus = await apiJson(page, `/api/status?taskId=${encodeURIComponent(job.taskId)}`);
    expect(restartedStatus.runs?.[0]?.run.id).toBe(remoteRun.id);
    const restartedJobs = await apiJson(page, '/api/jobs');
    expect(restartedJobs.jobs?.some((entry) => entry.id === job.id)).toBe(true);
    expect(restartedStatus.reservations?.some((reservation) => reservation.runId === remoteRun.id)).toBe(true);

    await fillDispatch(page, { taskId: job.taskId, approvalId, jobId: job.id });
    await expect(page.locator('#operation-status')).toContainText('Remote state uncertain');
    await expect(page.locator('#operation-status')).toContainText('Adapter invoked: no');
    expect(fake.reconcileCalls).toBeGreaterThan(0);
    expect(fake.dispatchCalls).toBe(2, 'restart/retry must not invoke the adapter for unresolved remote work');
  } finally {
    await server.close();
    delete process.env.AGENTSYS_STATE;
    rmSync(state, { recursive: true, force: true });
  }
});
